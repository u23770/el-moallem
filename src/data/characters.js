export const CHARACTER_MAP = Object.fromEntries(CHARACTERS.map((c) => [c.id, c]));
export function getCharacter(id) { return CHARACTER_MAP[id] ?? CHARACTERS[0]; }
export function pickLine(lines, rng = Math.random) {
  if (!lines?.length) return '';
  return lines[Math.floor(rng() * lines.length) % lines.length];
}
